// Rising embers: only while something is affected. Fixed seeds, so they don't
// jump between renders.
const EMBERS = Array.from({ length: 14 }, (_, i) => ({
  x: 6 + ((i * 37) % 88),
  size: 2 + (i % 3),
  delay: (i * 1.7) % 9,
  secs: 9 + (i % 5) * 2,
  sway: (i % 2 ? 1 : -1) * (10 + (i % 4) * 6),
}))

export function Scene({ reading }: { reading: Reading }) {
  const reduce = useReducedMotion()
  return (
    <div
      aria-hidden
      className="fw-scene"
      style={{ ['--fw-glow' as string]: glow[reading] } as CSSProperties}
    >
      <div className="fw-horizon" />
      <svg
        className="absolute inset-0 h-full w-full"
        viewBox="0 0 1600 900"
        preserveAspectRatio="xMidYMax slice"
      >
        {RIDGES.map((r, i) => (
          <motion.g
            key={i}
            animate={reduce ? undefined : { x: [-r.drift, r.drift] }}
            transition={{
              duration: r.secs,
              ease: 'easeInOut',
              repeat: Infinity,
              repeatType: 'mirror',
            }}
          >
            <path d={r.d} fill={r.fill} transform="translate(-60 0) scale(1.075 1)" />
            {i === 2 && (
              // The lookout tower on the near ridge.
              <g fill={r.fill} transform="translate(-60 0) scale(1.075 1)">
                <path d="M1349 682 L1355 646 L1357 646 L1353 682 Z M1371 682 L1365 646 L1363 646 L1367 682 Z M1353 668 H1367 V670 H1353 Z M1355 656 H1365 V658 H1355 Z" />
                <path d="M1351 633 H1369 V647 H1351 Z" />
                <path d="M1347 634 L1360 624 L1373 634 Z" />
                <rect x="1354" y="637" width="12" height="5" fill="var(--fw-glow)" />
              </g>
            )}
          </motion.g>
        ))}
      </svg>
      {reading === 'affected' && !reduce && (
        <div className="absolute inset-x-0 bottom-0 h-[60%] overflow-hidden">
          {EMBERS.map((e, i) => (
            <motion.span
              key={i}
              className="absolute bottom-0 rounded-full bg-[var(--fw-ember)]"
              style={{ left: `${e.x}%`, width: e.size, height: e.size }}
              initial={{ y: 0, opacity: 0 }}
              animate={{ y: [-10, -420], x: [0, e.sway], opacity: [0, 0.9, 0] }}
              transition={{ duration: e.secs, delay: e.delay, repeat: Infinity, ease: 'easeOut' }}
            />
          ))}
        </div>
      )}
      <div className="fw-grain" />
    </div>
  )
}
