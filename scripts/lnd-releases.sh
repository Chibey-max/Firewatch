#!/usr/bin/env bash
# Writes releases/lnd.toml: every official LND tag from v0.16 on, with the
# commit the tag points to. Firewatch compares a node's commit_hash with it.
#   scripts/lnd-releases.sh
set -euo pipefail
cd "$(dirname "$0")/.."

out=releases/lnd.toml
{
  echo "# Official LND releases: tag -> commit. Generated by scripts/lnd-releases.sh"
  echo "# from https://github.com/lightningnetwork/lnd on $(date -u +%Y-%m-%d). Do not edit by hand."
  echo
  echo "implementation = \"lnd\""
  # Annotated tags: the peeled line (^{}) is the commit the tag points to.
  git ls-remote --tags https://github.com/lightningnetwork/lnd \
      'refs/tags/v0.1[6-9]*' 'refs/tags/v0.2*' \
    | awk '$2 ~ /\^\{\}$/ { sub("refs/tags/", "", $2); sub(/\^\{\}$/, "", $2); print $2, $1 }' \
    | sort -V \
    | while read -r tag commit; do
        printf '\n[[release]]\nversion = "%s"\ncommit = "%s"\n' "$tag" "$commit"
      done
} > "$out"
echo "wrote $(grep -c '^\[\[release\]\]' "$out") releases to $out"
