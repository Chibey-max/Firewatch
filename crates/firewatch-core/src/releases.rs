//! The build check: does the node's binary come from the official release
//! its version number claims?
//!
//! A version string is just text a build prints. LND also reports the commit
//! it was built from, so Firewatch compares that with the commit the official
//! release tag points to. If they differ, the version number can't be trusted
//! and every finding on that node becomes "Can't tell".
//!
//! The commit alone isn't enough: LND takes `commit_hash` from Go's
//! `vcs.revision`, which is HEAD even when the source tree has uncommitted
//! changes. The only sign of those is the `commit=` part of the version
//! string (`git describe --tags --dirty`), so that must name an official tag
//! on the same commit too.

use std::path::Path;

use serde::{Deserialize, Serialize};

use crate::advisory::{Implementation, LoadError};
use crate::node::NodeInfo;
use crate::version::Version;

/// `releases/lnd.toml`, generated by `scripts/lnd-releases.sh`.
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ReleaseTable {
    pub implementation: Implementation,
    #[serde(rename = "release", default)]
    pub releases: Vec<Release>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Release {
    /// The tag, e.g. `v0.18.5-beta`.
    pub version: String,
    /// The full commit hash the tag points to.
    pub commit: String,
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "status", rename_all = "snake_case")]
pub enum BuildCheck {
    /// The node's commit is the official release commit.
    Match,
    /// The node claims a release version but was built from another commit,
    /// or from the right commit with changes (`actual` equals `expected` then).
    Mismatch {
        /// The tag the version number claims, e.g. `v0.20.0-beta`.
        release: String,
        expected: String,
        actual: String,
        /// How the node describes its build: LND's `commit=` text, e.g.
        /// `v0.20.0-beta-dirty`. Absent when the version string has none.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        build: Option<String>,
    },
    /// Core Lightning built from a commit that isn't a release: `git describe`
    /// added `-<n>-g<hash>`, e.g. `v26.06.7-12-gabc1234`. It may hold changes
    /// or fixes the release doesn't, so every finding becomes "Can't tell".
    Unreleased {
        /// The release tag the build started from, e.g. `v26.06.7`.
        release: String,
        /// The whole version string the node reports.
        build: String,
    },
    /// Core Lightning built from a release tag with local changes:
    /// `v26.06.7-modded`. A clean source build often gets this too, when the
    /// build regenerates tracked files (ElementsProject/lightning#7152), so
    /// red findings stay red and only "Not affected" becomes "Can't tell".
    Modified { release: String, build: String },
    /// The version isn't in the table, e.g. a release newer than the table.
    UnknownRelease,
    /// No table for this implementation, or the node reports no commit.
    #[default]
    NotChecked,
}

impl ReleaseTable {
    pub fn load(path: &Path) -> Result<Self, LoadError> {
        let text = std::fs::read_to_string(path).map_err(|source| LoadError::Io {
            path: path.to_path_buf(),
            source,
        })?;
        toml::from_str(&text).map_err(|e| LoadError::Parse {
            path: path.to_path_buf(),
            source: Box::new(e),
        })
    }

    /// The official release whose version equals `version`, if any.
    pub fn release(&self, version: &Version) -> Option<&Release> {
        self.releases_of(version).next()
    }

    /// Every official tag whose version equals `version`. Version equality
    /// ignores suffixes, so `v0.18.0-beta` and `v0.18.0-beta.1` are both here.
    fn releases_of(&self, version: &Version) -> impl Iterator<Item = &Release> {
        let version = version.clone();
        self.releases
            .iter()
            .filter(move |r| Version::parse(&r.version).is_ok_and(|v| v == version))
    }

    pub fn check(&self, node: &NodeInfo) -> BuildCheck {
        if node.implementation != self.implementation {
            return BuildCheck::NotChecked;
        }
        let (Some(actual), Ok(version)) = (&node.commit_hash, Version::parse(&node.version)) else {
            return BuildCheck::NotChecked;
        };
        let Some(claimed) = self.release(&version) else {
            return BuildCheck::UnknownRelease;
        };
        let build = described_build(&node.version);
        let mismatch = |release: &Release| BuildCheck::Mismatch {
            release: release.version.clone(),
            expected: release.commit.clone(),
            actual: actual.clone(),
            build: build.map(str::to_string),
        };
        let Some(same_commit) = self
            .releases_of(&version)
            .find(|r| r.commit.eq_ignore_ascii_case(actual))
        else {
            return mismatch(claimed);
        };
        // An official binary describes itself as a tag on its own commit;
        // `-dirty` or an empty `commit=` means it was built some other way.
        match build {
            Some(b)
                if !self
                    .releases
                    .iter()
                    .any(|r| r.version == b && r.commit.eq_ignore_ascii_case(actual)) =>
            {
                mismatch(same_commit)
            }
            _ => BuildCheck::Match,
        }
    }
}

/// The build check for any node. LND compares its commit with `releases`;
/// Core Lightning reports no commit, only what `git describe` added to its
/// version, so that's what it is checked on.
pub fn build_check(node: &NodeInfo, releases: Option<&ReleaseTable>) -> BuildCheck {
    match node.implementation {
        Implementation::Cln => cln_build_check(&node.version),
        _ => releases.map_or(BuildCheck::NotChecked, |t| t.check(node)),
    }
}

/// Core Lightning's version comes from `git describe --tags --always
/// --dirty=-modded --abbrev=7`; official releases pass the tag itself. Only
/// those two markers count: a packaging suffix such as `-umbrel` doesn't.
fn cln_build_check(version: &str) -> BuildCheck {
    let build = version.trim();
    let (described, modded) = match build.strip_suffix("-modded") {
        Some(rest) => (rest, true),
        None => (build, false),
    };
    let unreleased_tag = {
        let mut parts = described.rsplitn(3, '-');
        match (parts.next(), parts.next(), parts.next()) {
            (Some(hash), Some(commits), Some(tag))
                if !commits.is_empty()
                    && commits.bytes().all(|b| b.is_ascii_digit())
                    && hash.len() >= 5
                    && hash.starts_with('g')
                    && hash[1..].bytes().all(|b| b.is_ascii_hexdigit()) =>
            {
                Some(tag)
            }
            _ => None,
        }
    };
    let release = unreleased_tag.unwrap_or(described);
    // A bare commit hash (`--always` without tags) names no release at all;
    // the engine already says "Can't tell" for a version it can't parse.
    if Version::parse(release).is_err() {
        return BuildCheck::NotChecked;
    }
    let (release, build) = (release.to_string(), build.to_string());
    match (unreleased_tag, modded) {
        (Some(_), _) => BuildCheck::Unreleased { release, build },
        (None, true) => BuildCheck::Modified { release, build },
        (None, false) => BuildCheck::NotChecked,
    }
}

/// LND's `commit=` text from its version string, e.g. `v0.20.0-beta` in
/// `0.20.0-beta commit=v0.20.0-beta`. `None` when there is no `commit=`.
fn described_build(version: &str) -> Option<&str> {
    version
        .split_whitespace()
        .find_map(|t| t.strip_prefix("commit="))
}

/// The first 7 characters of a commit hash, as git shows it. Safe on any
/// text, since the hash comes from the node.
pub fn short_commit(hash: &str) -> &str {
    hash.char_indices().nth(7).map_or(hash, |(i, _)| &hash[..i])
}

#[cfg(test)]
mod tests {
    use super::*;

    const OFFICIAL: &str = "4ccf4fc24c750d098cf24566ef4bbc0311c7d476";

    fn table() -> ReleaseTable {
        toml::from_str(&format!(
            r#"
            implementation = "lnd"
            [[release]]
            version = "v0.18.5-beta.rc1"
            commit = "288f0e1b3dc877c3ac8fefdb61af32284a296b3f"
            [[release]]
            version = "v0.18.5-beta"
            commit = "{OFFICIAL}"
            "#
        ))
        .unwrap()
    }

    fn node(version: &str, commit: Option<&str>) -> NodeInfo {
        NodeInfo {
            name: "n".into(),
            implementation: Implementation::Lnd,
            version: version.into(),
            network: None,
            config: None,
            features: None,
            commit_hash: commit.map(str::to_string),
        }
    }

    #[test]
    fn official_build_matches() {
        let n = node("0.18.5-beta commit=v0.18.5-beta", Some(OFFICIAL));
        assert_eq!(table().check(&n), BuildCheck::Match);
    }

    #[test]
    fn other_commit_is_a_mismatch() {
        let n = node(
            "0.18.5-beta commit=v0.18.5-beta-1-g1234567",
            Some("1234567890abcdef1234567890abcdef12345678"),
        );
        assert!(matches!(
            table().check(&n),
            BuildCheck::Mismatch { release, .. } if release == "v0.18.5-beta"
        ));
    }

    #[test]
    fn release_candidate_is_its_own_release() {
        let n = node("0.18.5-beta.rc1", Some(OFFICIAL));
        assert!(matches!(table().check(&n), BuildCheck::Mismatch { .. }));
    }

    #[test]
    fn version_missing_from_table_is_unknown() {
        let n = node("0.21.1-beta", Some(OFFICIAL));
        assert_eq!(table().check(&n), BuildCheck::UnknownRelease);
    }

    #[test]
    fn no_commit_or_other_implementation_is_not_checked() {
        assert_eq!(
            table().check(&node("0.18.5-beta", None)),
            BuildCheck::NotChecked
        );
        let mut cln = node("v26.06.7", Some(OFFICIAL));
        cln.implementation = Implementation::Cln;
        assert_eq!(table().check(&cln), BuildCheck::NotChecked);
    }

    #[test]
    fn official_commit_with_local_changes_is_a_mismatch() {
        let n = node("0.18.5-beta commit=v0.18.5-beta-dirty", Some(OFFICIAL));
        assert_eq!(
            table().check(&n),
            BuildCheck::Mismatch {
                release: "v0.18.5-beta".into(),
                expected: OFFICIAL.into(),
                actual: OFFICIAL.into(),
                build: Some("v0.18.5-beta-dirty".into()),
            }
        );
    }

    #[test]
    fn official_commit_without_release_flags_is_a_mismatch() {
        // `go build` without the Makefile leaves `commit=` empty, so nothing
        // says whether the tree was clean.
        let n = node("0.18.5-beta commit=", Some(OFFICIAL));
        assert!(matches!(
            table().check(&n),
            BuildCheck::Mismatch { build: Some(b), .. } if b.is_empty()
        ));
    }

    #[test]
    fn another_official_tag_on_the_same_commit_matches() {
        // Real case: v0.18.0-beta and v0.18.0-beta.1 tag the same commit, and
        // git describe may name either.
        let t: ReleaseTable = toml::from_str(
            r#"
            implementation = "lnd"
            [[release]]
            version = "v0.18.0-beta"
            commit = "fed760913ff98a89c73414acde6cf29f8728321a"
            [[release]]
            version = "v0.18.0-beta.1"
            commit = "fed760913ff98a89c73414acde6cf29f8728321a"
            "#,
        )
        .unwrap();
        let n = node(
            "0.18.0-beta commit=v0.18.0-beta.1",
            Some("fed760913ff98a89c73414acde6cf29f8728321a"),
        );
        assert_eq!(t.check(&n), BuildCheck::Match);
    }

    #[test]
    fn every_tag_with_the_version_is_considered() {
        // Two tags that parse to the same version but point at different
        // commits: a build of either is official.
        let t: ReleaseTable = toml::from_str(&format!(
            r#"
            implementation = "lnd"
            [[release]]
            version = "v0.18.5-beta"
            commit = "{OFFICIAL}"
            [[release]]
            version = "v0.18.5-beta.1"
            commit = "1111111111111111111111111111111111111111"
            "#
        ))
        .unwrap();
        let n = node(
            "0.18.5-beta commit=v0.18.5-beta.1",
            Some("1111111111111111111111111111111111111111"),
        );
        assert_eq!(t.check(&n), BuildCheck::Match);

        // A changed build of that second commit names that tag, not the
        // first one, so the report doesn't claim the commit differs.
        let n = node(
            "0.18.5-beta commit=v0.18.5-beta.1-dirty",
            Some("1111111111111111111111111111111111111111"),
        );
        assert!(matches!(
            t.check(&n),
            BuildCheck::Mismatch { release, expected, actual, .. }
                if release == "v0.18.5-beta.1" && expected == actual
        ));
    }

    fn cln(version: &str) -> BuildCheck {
        let mut n = node(version, None);
        n.implementation = Implementation::Cln;
        build_check(&n, Some(&table()))
    }

    #[test]
    fn cln_release_builds_are_not_checked() {
        // What the official images report (elementsproject/lightningd,
        // polarlightning/clightning), and a release candidate tag.
        for v in ["v26.06.7", "v26.06.9", "v25.12", "v26.06rc1"] {
            assert_eq!(cln(v), BuildCheck::NotChecked, "{v}");
        }
    }

    #[test]
    fn cln_built_after_a_tag_is_unreleased() {
        for (v, release) in [
            ("v26.06.7-12-gabc1234", "v26.06.7"),
            ("v26.06.7-12-gabc1234-modded", "v26.06.7"),
            ("v26.06rc1-3-g1a2b", "v26.06rc1"),
        ] {
            assert_eq!(
                cln(v),
                BuildCheck::Unreleased {
                    release: release.into(),
                    build: v.into()
                },
                "{v}"
            );
        }
    }

    #[test]
    fn cln_with_local_changes_is_modified() {
        assert_eq!(
            cln("v26.06.7-modded"),
            BuildCheck::Modified {
                release: "v26.06.7".into(),
                build: "v26.06.7-modded".into()
            }
        );
    }

    #[test]
    fn other_cln_suffixes_are_not_git_markers() {
        // A packaging suffix, a hash that isn't hex, a count that isn't a
        // number, and a bare commit hash (`--always` without tags).
        for v in [
            "v26.06.8-umbrel",
            "v26.06.7-12-gxyz1234",
            "v26.06.7-x-gabc1234",
            "abc1234",
            "abc1234-modded",
        ] {
            assert_eq!(cln(v), BuildCheck::NotChecked, "{v}");
        }
    }

    #[test]
    fn lnd_is_still_checked_against_the_table() {
        let n = node("0.18.5-beta commit=v0.18.5-beta-modded", Some(OFFICIAL));
        assert!(matches!(
            build_check(&n, Some(&table())),
            BuildCheck::Mismatch { .. }
        ));
        assert_eq!(build_check(&n, None), BuildCheck::NotChecked);
    }

    #[test]
    fn short_commit_never_splits_a_character() {
        assert_eq!(short_commit(OFFICIAL), "4ccf4fc");
        assert_eq!(short_commit("abc"), "abc");
        assert_eq!(short_commit("éééééééééé"), "ééééééé");
    }

    #[test]
    fn generated_table_loads() {
        let path =
            std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../releases/lnd.toml");
        let t = ReleaseTable::load(&path).unwrap();
        let v = Version::parse("0.20.0-beta").unwrap();
        assert_eq!(
            t.release(&v).unwrap().commit,
            "b9ea7070c20ad2ca8514a47d9b4d560a501f0487"
        );
    }
}
