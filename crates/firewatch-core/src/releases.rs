//! The build check: does the node's binary come from the official release
//! its version number claims?
//!
//! A version string is just text a build prints. LND also reports the commit
//! it was built from, so Firewatch compares that with the commit the official
//! release tag points to. If they differ, the version number can't be trusted
//! and every finding on that node becomes "Can't tell".

use std::path::Path;

use serde::{Deserialize, Serialize};

use crate::advisory::{Implementation, LoadError};
use crate::node::NodeInfo;
use crate::version::Version;

/// `releases/lnd.toml`, generated by `scripts/lnd-releases.sh`.
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ReleaseTable {
    pub implementation: Implementation,
    #[serde(rename = "release", default)]
    pub releases: Vec<Release>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Release {
    /// The tag, e.g. `v0.18.5-beta`.
    pub version: String,
    /// The full commit hash the tag points to.
    pub commit: String,
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "status", rename_all = "snake_case")]
pub enum BuildCheck {
    /// The node's commit is the official release commit.
    Match,
    /// The node claims a release version but was built from another commit.
    Mismatch {
        /// The tag the version number claims, e.g. `v0.20.0-beta`.
        release: String,
        expected: String,
        actual: String,
    },
    /// The version isn't in the table, e.g. a release newer than the table.
    UnknownRelease,
    /// No table for this implementation, or the node reports no commit.
    #[default]
    NotChecked,
}

impl ReleaseTable {
    pub fn load(path: &Path) -> Result<Self, LoadError> {
        let text = std::fs::read_to_string(path).map_err(|source| LoadError::Io {
            path: path.to_path_buf(),
            source,
        })?;
        toml::from_str(&text).map_err(|e| LoadError::Parse {
            path: path.to_path_buf(),
            source: Box::new(e),
        })
    }

    /// The official release whose version equals `version`, if any.
    pub fn release(&self, version: &Version) -> Option<&Release> {
        self.releases
            .iter()
            .find(|r| Version::parse(&r.version).is_ok_and(|v| v == *version))
    }

    pub fn check(&self, node: &NodeInfo) -> BuildCheck {
        if node.implementation != self.implementation {
            return BuildCheck::NotChecked;
        }
        let (Some(actual), Ok(version)) = (&node.commit_hash, Version::parse(&node.version)) else {
            return BuildCheck::NotChecked;
        };
        match self.release(&version) {
            None => BuildCheck::UnknownRelease,
            Some(r) if r.commit.eq_ignore_ascii_case(actual) => BuildCheck::Match,
            Some(r) => BuildCheck::Mismatch {
                release: r.version.clone(),
                expected: r.commit.clone(),
                actual: actual.clone(),
            },
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const OFFICIAL: &str = "4ccf4fc24c750d098cf24566ef4bbc0311c7d476";

    fn table() -> ReleaseTable {
        toml::from_str(&format!(
            r#"
            implementation = "lnd"
            [[release]]
            version = "v0.18.5-beta.rc1"
            commit = "288f0e1b3dc877c3ac8fefdb61af32284a296b3f"
            [[release]]
            version = "v0.18.5-beta"
            commit = "{OFFICIAL}"
            "#
        ))
        .unwrap()
    }

    fn node(version: &str, commit: Option<&str>) -> NodeInfo {
        NodeInfo {
            name: "n".into(),
            implementation: Implementation::Lnd,
            version: version.into(),
            network: None,
            config: None,
            features: None,
            commit_hash: commit.map(str::to_string),
        }
    }

    #[test]
    fn official_build_matches() {
        let n = node("0.18.5-beta commit=v0.18.5-beta", Some(OFFICIAL));
        assert_eq!(table().check(&n), BuildCheck::Match);
    }

    #[test]
    fn other_commit_is_a_mismatch() {
        let n = node(
            "0.18.5-beta commit=v0.18.5-beta-1-g1234567",
            Some("1234567890abcdef1234567890abcdef12345678"),
        );
        assert!(matches!(
            table().check(&n),
            BuildCheck::Mismatch { release, .. } if release == "v0.18.5-beta"
        ));
    }

    #[test]
    fn release_candidate_is_its_own_release() {
        let n = node("0.18.5-beta.rc1", Some(OFFICIAL));
        assert!(matches!(table().check(&n), BuildCheck::Mismatch { .. }));
    }

    #[test]
    fn version_missing_from_table_is_unknown() {
        let n = node("0.21.1-beta", Some(OFFICIAL));
        assert_eq!(table().check(&n), BuildCheck::UnknownRelease);
    }

    #[test]
    fn no_commit_or_other_implementation_is_not_checked() {
        assert_eq!(
            table().check(&node("0.18.5-beta", None)),
            BuildCheck::NotChecked
        );
        let mut cln = node("v26.06.7", Some(OFFICIAL));
        cln.implementation = Implementation::Cln;
        assert_eq!(table().check(&cln), BuildCheck::NotChecked);
    }

    #[test]
    fn generated_table_loads() {
        let path =
            std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../releases/lnd.toml");
        let t = ReleaseTable::load(&path).unwrap();
        let v = Version::parse("0.20.0-beta").unwrap();
        assert_eq!(
            t.release(&v).unwrap().commit,
            "b9ea7070c20ad2ca8514a47d9b4d560a501f0487"
        );
    }
}
